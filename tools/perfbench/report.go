package main

import (
	"fmt"
	"slices"
	"strings"
	"text/tabwriter"
	"time"
)

// result is one store's complete measurement: its size, its bytes on disk, and
// one sample per probe.
type result struct {
	size size
	// imported is how long `lit import` took to build the measured store, one
	// run: the slope of lit's write path as a single figure.
	imported time.Duration
	bytes    int64
	// fleetBytes is every store of the scale point on disk, the measured one
	// included: bytes again for a single store, the machine's disk for a
	// fleet.
	fleetBytes int64
	// compacted is the store's bytes after every probe and a full
	// compaction: what its rows cost to keep.
	compacted int64
	samples   []sample
	// history is what historyEdits single-row edits added, zero for a store
	// with no row to edit.
	history historyCost
}

// conditions is the machine the run happened on. It is passed in rather than
// read here so the report stays a pure function of its inputs and its tests
// need no machine to agree with. [LAW:effects-at-boundaries]
type conditions struct {
	goos   string
	goarch string
	cpus   int
}

// renderReport turns measurements into the table, and is deliberately the only
// part of this tool that decides what the output looks like — no subprocess, no
// clock, no filesystem, so the format is testable against fixed samples rather
// than against a store somebody has to build first. [LAW:effects-at-boundaries]
//
// Sizes are columns and probes are rows because the question the scale epic asks
// is how a command's cost moves with the store: reading across one row answers
// it directly, and a per-size block layout would make the reader hold three
// numbers in their head to see it.
//
// The rows are the probes, in the order they run, and each cell is looked up
// by probe name: a store can lack a probe (the empty control has no row for
// `show` to name), and reading cells by position would shift every later
// figure under the wrong command's name with nothing to say so.
// [LAW:types-are-the-program]
//
// found is the verdict run exits on, passed in rather than judged again here,
// so the BUDGET section is the list that set the exit status.
// [LAW:one-source-of-truth]
func renderReport(ps []probe, results []result, budget time.Duration, found []breach, cond conditions) string {
	var b strings.Builder
	fmt.Fprintf(&b, "lit perfbench — %s/%s, %d CPUs\n", cond.goos, cond.goarch, cond.cpus)
	fmt.Fprintf(&b, "%d repeats per probe, round-robin after one unrecorded warm-up; the figure is the MIN, the max is in parentheses.\n", repeats)
	b.WriteString("A max near the min is a quiet machine and a trustworthy figure. A max several\n")
	b.WriteString("times the min means the run was competing for CPU and only the min survived it.\n")
	b.WriteString("Stores are generated by `lit init` + `lit import`; the binary is built from the\n")
	b.WriteString("working tree, never taken from PATH.\n\n")

	w := tabwriter.NewWriter(&b, 0, 0, 2, ' ', 0)
	fmt.Fprint(w, "COMMAND")
	for _, r := range results {
		fmt.Fprintf(w, "\t%s", r.size)
	}
	fmt.Fprintln(w)

	for _, p := range measuredRows(ps, results) {
		fmt.Fprint(w, p.name)
		for _, r := range results {
			fmt.Fprintf(w, "\t%s", formatCell(r, p.name))
		}
		fmt.Fprintln(w)
	}
	fmt.Fprint(w, "import")
	for _, r := range results {
		fmt.Fprintf(w, "\t%s", formatDuration(r.imported))
	}
	fmt.Fprintln(w)
	fmt.Fprint(w, "store bytes")
	for _, r := range results {
		fmt.Fprintf(w, "\t%s", formatBytes(r.bytes))
	}
	fmt.Fprintln(w)
	fmt.Fprint(w, "fleet bytes")
	for _, r := range results {
		fmt.Fprintf(w, "\t%s", formatBytes(r.fleetBytes))
	}
	fmt.Fprintln(w)
	fmt.Fprint(w, "compacted bytes")
	for _, r := range results {
		fmt.Fprintf(w, "\t%s", formatBytes(r.compacted))
	}
	fmt.Fprintln(w)
	fmt.Fprint(w, "bytes/commit")
	for _, r := range results {
		fmt.Fprintf(w, "\t%s", formatHistory(r.history))
	}
	fmt.Fprintln(w)
	w.Flush()
	b.WriteString("\nimport is how long `lit import` took to load the measured store's rows, one run.\n")
	b.WriteString("store bytes is the store as imported. fleet bytes is every store of its column, row\n")
	b.WriteString("data only: no snapshots, no remote cache, and no history but the import's. compacted\n")
	b.WriteString("bytes is the store after the probes and a full compaction, which collects the\n")
	b.WriteString("import's garbage. bytes/commit is\n")
	fmt.Fprintf(&b, "the store's growth across %d single-row edits, one commit each, measured after a\n", historyEdits)
	b.WriteString("full compaction on both sides, so it is history the store keeps.\n")

	fmt.Fprintf(&b, "\nBUDGET: every probe under %s, judged on its min.\n", budget)
	for _, br := range found {
		fmt.Fprintf(&b, "  OVER  %s\n", br)
	}
	if len(found) == 0 {
		b.WriteString("  none over budget\n")
	}
	return b.String()
}

// measuredRows is the probes to print a row for, in the order they ran (reads,
// then writes) and only those some store measured, so a report over nothing
// names no probe: a header of names no column was measured for is a report
// that looks like a result.
func measuredRows(ps []probe, results []result) []probe {
	var rows []probe
	for _, p := range slices.Concat(phasesOf(ps, func(p probe) probe { return p })...) {
		for _, r := range results {
			if _, ok := r.sample(p.name); ok {
				rows = append(rows, p)
				break
			}
		}
	}
	return rows
}

// sample is r's sample of the named probe, or false when r has none.
func (r result) sample(name string) (sample, bool) {
	for _, s := range r.samples {
		if s.probe.name == name {
			return s, true
		}
	}
	return sample{}, false
}

// formatCell prints one probe's figure against one store: its min and, in
// parentheses, its max; the run it was killed in; or a dash where the store
// admitted no invocation of it.
func formatCell(r result, name string) string {
	s, ok := r.sample(name)
	if !ok {
		return "—"
	}
	switch o := s.outcome.(type) {
	case completed:
		return fmt.Sprintf("%s (%s)", formatDuration(o.min), formatDuration(o.max))
	case killed:
		return fmt.Sprintf("killed (%s, >%s)", roundName(o.round), formatDuration(o.after))
	default:
		panic(fmt.Sprintf("formatCell: unknown outcome %T", s.outcome))
	}
}

// formatHistory prints one commit's cost, or a dash for a store that had no
// row to edit and so measured none.
func formatHistory(h historyCost) string {
	if h.edits == 0 {
		return "—"
	}
	return formatBytes(h.perCommit())
}

// formatDuration prints seconds to two decimals, matching the units the scale
// epic states its own figures in ("lit backlog 7.97s") so a regenerated table
// can be compared to the pasted one without converting anything. Sub-second
// costs are the point of the epic, and 0.07s reads as a fraction of a budget in
// a way 70ms does not.
func formatDuration(d time.Duration) string {
	return fmt.Sprintf("%.2fs", d.Seconds())
}

// formatBytes prints against the epic's own 50 MB ceiling and its 188 MB
// observation, both stated in MB. Decimal MB, not MiB: the figures this is
// compared against came from `du`-style reporting, and silently switching base
// would move every number by 5%.
//
// Below a megabyte it switches to KB, which costs a little column scannability
// and buys the empty store an honest figure. The empty store is the control for
// lit's fixed on-disk cost, and at two decimals of MB every such store prints
// "0.00 MB" — a real four-kilobyte number rendered as zero, which is the one
// reading a reader must not take from it. Nothing near the ceiling the epic
// cares about is affected: those all print in MB.
func formatBytes(n int64) string {
	if n < 1e6 {
		return fmt.Sprintf("%.2f KB", float64(n)/1e3)
	}
	return fmt.Sprintf("%.2f MB", float64(n)/1e6)
}
